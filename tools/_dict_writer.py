"""Shared writer for the extra language columns of i18n-data.js.

The English, German and Bosnian columns live in the markup. Every other
language lives in its own file under tools/:

    tools/italian.py   Italian
    tools/french.py    French
    tools/dutch.py     Dutch

Each of those scripts calls write_column() with its own language code and
its own values. The writer reads the dictionary, replaces that ONE column
and writes the file back with every column still there - so running the
Italian script never removes French or Dutch.

The file is written in the original key order, so a run never changes the
English, German or Bosnian values.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DICT = ROOT / "i18n-data.js"

# The columns that come from the markup, in the order they are written.
BASE = ["en", "de", "bs"]
# The extra languages, in the order they are written.
EXTRA = ["it", "fr", "nl"]

HEAD = (
    "/* Pliva River Lodge - i18n dictionary. Generated by tools/italian.py,\n"
    "   tools/french.py and tools/dutch.py; do not edit by hand. */\n"
)


def load():
    """The dictionary as it is on disk."""
    raw = DICT.read_text(encoding="utf-8")
    body = raw[raw.index("{") : raw.rindex("}") + 1]
    return json.loads(body)


def write_column(lang, values, label):
    """Replace one language column and write the dictionary back.

    Returns 0 on success, 1 if a key is missing or unknown.
    """
    data = load()

    missing = sorted(set(data) - set(values))
    extra = sorted(set(values) - set(data))
    if missing:
        print(f"ERROR: no {label} for: {', '.join(missing)}")
        return 1
    if extra:
        print(f"ERROR: {label} for unknown keys: {', '.join(extra)}")
        return 1

    # Work out what each key should hold, column by column.
    columns = {}
    for key, entry in data.items():
        columns[key] = {}
        for base in BASE:
            columns[key][base] = entry.get(base, "")
        for other in EXTRA:
            if other == lang:
                columns[key][other] = values[key]
            elif other in entry:
                columns[key][other] = entry[other]

    out = [HEAD, "window.I18N = {\n"]
    keys = list(columns.keys())
    for i, key in enumerate(keys):
        out.append(f'  "{key}": {{\n')
        entries = columns[key]
        names = BASE + [x for x in EXTRA if x in entries]
        for j, name in enumerate(names):
            comma = "," if j < len(names) - 1 else ""
            value = json.dumps(entries[name], ensure_ascii=False)
            out.append(f'    "{name}": {value}{comma}\n')
        out.append("  }" + ("," if i < len(keys) - 1 else "") + "\n")
    out.append("};\n")

    DICT.write_text("".join(out), encoding="utf-8")
    print(f"Wrote {len(keys)} keys with the {label} column.")
    return 0
